"""
DESIGN.md §7 — the IMU bias walk: an exact Gauss-Markov process on top of the constant
bias trait, generated by SkyFlow-Dynamics (imu_stochastic_errors, verified against the
executed rl-tools L2F) and advanced once per control step. CPU motors-mode fleets only.
"""

import math

import jax
import jax.numpy as jnp
import numpy as np
import pytest

from skyflow import dynamics
from skyflow.env import DomainRand, SimConfig, SkyFlowEnv

FLEET = 2048
DT = 0.01  # control step at 100 Hz


def _env(fleet=FLEET, scale=1.0, **dr):
    dr = DomainRand(scale=scale, body_scale=0.0, **dr)
    cfg = SimConfig(num_envs=fleet, airframe="crazyflie", task="hover", control="motors",
                    physics_hz=1000, control_hz=100.0, max_episode_steps=10_000, dr=dr)
    return SkyFlowEnv(cfg)


def _hover_action(env):
    return jnp.zeros((env.fleet, 4), jnp.float32)


def _walk_after(env, steps, seed=0):
    _, state = env.reset(jax.random.PRNGKey(seed))
    step = jax.jit(env.step)
    a = _hover_action(env)
    for _ in range(steps):
        _, state, _, _, _ = step(state, a)
    return state, np.asarray(state.dr_state.imu_bias_walk)


def test_adapter_matches_the_closed_form():
    """dynamics.imu_bias_step is the exact OU step, with one density per column."""
    b = jnp.asarray([[0.02, -0.01, 0.0, 0.3, -0.2, 0.1]], jnp.float32)
    w = jnp.asarray([[1.0, -2.0, 0.5, 0.0, 1.5, -1.0]], jnp.float32)
    sigma = jnp.asarray([0.1] * 3 + [0.4] * 3, jnp.float32)
    tau, dt = 2.0, 0.01
    got = np.asarray(dynamics.imu_bias_step(b, w, tau, sigma, dt))
    alpha = math.exp(-dt / tau)
    sd = np.asarray(sigma) * math.sqrt(tau / 2 * -math.expm1(-2 * dt / tau))
    np.testing.assert_allclose(got, alpha * np.asarray(b) + sd * np.asarray(w), rtol=2e-6)
    assert got.dtype == np.float32


def test_adapter_long_tau_is_a_random_walk_in_float32():
    """τ ≫ dt: the step keeps its driving noise in float32 — b' = b + sigma·√dt·w."""
    b = jnp.zeros((1, 6), jnp.float32)
    w = jnp.ones((1, 6), jnp.float32)
    got = np.asarray(dynamics.imu_bias_step(b, w, 1e9, 0.5, 1e-3))
    np.testing.assert_allclose(got, 0.5 * math.sqrt(1e-3), rtol=1e-5)


def test_off_by_default_the_walk_leaf_stays_zero():
    env = _env(fleet=8)
    _, walk = _walk_after(env, 5)
    assert not env._bias_walk_on
    np.testing.assert_array_equal(walk, 0.0)


def test_walk_statistics_match_the_ou_process():
    """After t seconds the fleet's walk std is sigma·√(τ/2·(1 - e^(-2t/τ))), per sensor."""
    tau, steps = 0.5, 40
    env = _env(gyro_bias_walk=0.02, accel_bias_walk=0.5, imu_bias_tau_s=tau)
    _, walk = _walk_after(env, steps)
    growth = math.sqrt(tau / 2 * (1 - math.exp(-2 * steps * DT / tau)))
    accel_std, gyro_std = walk[:, :3].std(), walk[:, 3:].std()
    assert accel_std == pytest.approx(0.5 * growth, rel=0.05)
    assert gyro_std == pytest.approx(0.02 * growth, rel=0.05)
    assert abs(walk.mean()) < 0.02 * accel_std        # zero-mean
    assert np.abs(np.corrcoef(walk.T) - np.eye(6)).max() < 0.1   # axes independent


def test_long_tau_grows_like_a_random_walk():
    env = _env(gyro_bias_walk=0.02, imu_bias_tau_s=1e6)
    _, walk = _walk_after(env, 25)
    assert walk[:, 3:].std() == pytest.approx(0.02 * math.sqrt(25 * DT), rel=0.05)
    np.testing.assert_array_equal(walk[:, :3], 0.0)   # accel density is zero


def test_master_scale_folds_into_the_densities():
    full = _walk_after(_env(gyro_bias_walk=0.02, imu_bias_tau_s=0.5), 10)[1]
    half = _walk_after(_env(scale=0.5, gyro_bias_walk=0.02, imu_bias_tau_s=0.5), 10)[1]
    np.testing.assert_allclose(half, 0.5 * full, rtol=1e-5, atol=1e-9)
    env0 = _env(fleet=8, scale=0.0, gyro_bias_walk=0.02)
    assert not env0._bias_walk_on                      # off(): bit-exact nominal


def test_measurement_carries_trait_plus_walk():
    """The IMU rows read constant bias + walk; the walk leaves the trait untouched."""
    env = _env(fleet=16, gyro_bias_rps=0.05, accel_bias_mps2=0.3,
               gyro_bias_walk=0.02, accel_bias_walk=0.5, imu_bias_tau_s=0.5)
    _, state0 = env.reset(jax.random.PRNGKey(3))
    state, walk = _walk_after(env, 20, seed=3)
    np.testing.assert_array_equal(np.asarray(state.dr_state.imu_bias),
                                  np.asarray(state0.dr_state.imu_bias))
    assert np.abs(walk).max() > 0
    omega = state.plant[:, 13:17]
    wind = jnp.zeros((16, 3), jnp.float32)
    exact = dynamics.imu(state.plant, omega, wind, state.params)
    accel, gyro = env._measure(state.plant, omega, wind, state.params, state.dr_state,
                               jax.random.PRNGKey(0))
    total = np.asarray(state.dr_state.imu_bias) + walk
    np.testing.assert_allclose(np.asarray(accel) - np.asarray(exact[0]), total[:, :3],
                               atol=2e-5)
    np.testing.assert_allclose(np.asarray(gyro) - np.asarray(exact[1]), total[:, 3:],
                               atol=2e-6)


def test_respawn_restarts_the_walk():
    """A finished episode respawns with a zero walk; live worlds keep theirs."""
    dr = DomainRand(body_scale=0.0, gyro_bias_walk=0.02, imu_bias_tau_s=0.5)
    cfg = SimConfig(num_envs=64, airframe="crazyflie", task="hover", control="motors",
                    physics_hz=1000, control_hz=100.0, max_episode_steps=6, dr=dr)
    env = SkyFlowEnv(cfg)
    _, state = env.reset(jax.random.PRNGKey(1))
    step = jax.jit(env.step)
    a = _hover_action(env)
    done = jnp.zeros(64, bool)
    for _ in range(6):
        assert not bool(done.any())
        assert int(state.steps.max()) < 6
        _, state, _, done, _ = step(state, a)
    assert bool(done.all())                            # truncated at max_episode_steps
    np.testing.assert_array_equal(np.asarray(state.dr_state.imu_bias_walk), 0.0)
    _, state, _, _, _ = step(state, a)
    assert np.abs(np.asarray(state.dr_state.imu_bias_walk)[:, 3:]).max() > 0


def test_config_guards():
    with pytest.raises(ValueError, match="gyro_bias_walk"):
        _env(fleet=2, gyro_bias_walk=-1.0)
    with pytest.raises(ValueError, match="imu_bias_tau_s"):
        _env(fleet=2, imu_bias_tau_s=0.0)
